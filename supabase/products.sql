create table if not exists public.products (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 100),
  description text not null check (char_length(description) between 1 and 1000),
  price numeric(12, 2) not null check (price >= 0),
  category text not null check (category in ('Elektronik', 'Furniture', 'Kitchen', 'Lainnya')),
  condition text not null check (
    condition in ('Baru', 'Bekas - seperti baru', 'Bekas - layak pakai')
  ),
  image_url text not null,
  seller_name text not null,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;

drop policy if exists "Products are visible to everyone" on public.products;
create policy "Products are visible to everyone"
  on public.products
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Authenticated users can create their own products" on public.products;
create policy "Authenticated users can create their own products"
  on public.products
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

grant select on public.products to anon, authenticated;
grant insert on public.products to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;
