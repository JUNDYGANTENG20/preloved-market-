create table if not exists public.users (
  id bigint generated by default as identity primary key,
  auth_user_id uuid references auth.users (id) on delete cascade,
  username text not null,
  email text not null,
  created_at timestamptz not null default now()
);

alter table public.users
  add column if not exists auth_user_id uuid,
  add column if not exists username text,
  add column if not exists email text,
  add column if not exists created_at timestamptz;

update public.users
set email = coalesce(email, ''),
    username = coalesce(
      nullif(trim(username), ''),
      nullif(split_part(coalesce(email, ''), '@', 1), ''),
      'user'
    ),
    created_at = coalesce(created_at, now());

alter table public.users
  alter column username set default 'user',
  alter column username set not null,
  alter column email set default '',
  alter column email set not null,
  alter column created_at set default now(),
  alter column created_at set not null;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.users'::regclass
      and conname = 'users_auth_user_id_fkey'
  ) then
    alter table public.users
      add constraint users_auth_user_id_fkey
      foreign key (auth_user_id) references auth.users (id) on delete cascade;
  end if;
end;
$$;

update public.users as profile
set auth_user_id = auth_user.id
from auth.users as auth_user
where profile.auth_user_id is null
  and lower(trim(profile.email)) = lower(trim(auth_user.email))
  and (
    select count(*)
    from public.users as same_email
    where lower(trim(same_email.email)) = lower(trim(profile.email))
  ) = 1;

create unique index if not exists users_auth_user_id_uidx
  on public.users (auth_user_id);

alter table public.users enable row level security;

drop policy if exists "Users can read their own profile" on public.users;
create policy "Users can read their own profile"
  on public.users
  for select
  to authenticated
  using ((select auth.uid()) = auth_user_id);

grant select on public.users to authenticated;

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  profile_id_type text;
  profile_id_default text;
begin
  select data_type, column_default
  into profile_id_type, profile_id_default
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'users'
    and column_name = 'id';

  if profile_id_type = 'uuid' then
    insert into public.users (id, auth_user_id, username, email)
    values (
      new.id,
      new.id,
      coalesce(
        nullif(trim(new.raw_user_meta_data ->> 'username'), ''),
        nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
        'user'
      ),
      coalesce(new.email, '')
    )
    on conflict (auth_user_id) do update
      set username = excluded.username,
          email = excluded.email;
  else
    if profile_id_default is null then
      raise exception 'public.users.id perlu identity/sequence agar profil dapat dibuat otomatis';
    end if;

    insert into public.users (auth_user_id, username, email)
    values (
      new.id,
      coalesce(
        nullif(trim(new.raw_user_meta_data ->> 'username'), ''),
        nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
        'user'
      ),
      coalesce(new.email, '')
    )
    on conflict (auth_user_id) do update
      set username = excluded.username,
          email = excluded.email;
  end if;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_auth_user();

insert into public.users (auth_user_id, username, email)
select
  auth_user.id,
  coalesce(
    nullif(trim(auth_user.raw_user_meta_data ->> 'username'), ''),
    nullif(split_part(coalesce(auth_user.email, ''), '@', 1), ''),
    'user'
  ),
  coalesce(auth_user.email, '')
from auth.users as auth_user
on conflict (auth_user_id) do update
  set username = excluded.username,
      email = excluded.email;
